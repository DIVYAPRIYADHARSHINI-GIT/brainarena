// Builds src/lib/wordlist.generated.ts for Word Hunt.
//
//   npm run words
//
// ANSWERS: a hand-picked list of common, family-friendly 5-letter words.
// VALID GUESSES: answers + lowercase 5-letter words from the system dictionary
// (/usr/share/dict/words on macOS/Linux) + simple plurals of 4-letter words.
// The output is committed, so builds (e.g. on Vercel) never need the dictionary.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

